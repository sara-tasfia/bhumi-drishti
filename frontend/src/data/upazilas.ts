export function getUpazilasByDistrict(districtId: string): Upazila[] {
  return UPAZILAS.filter(u => u.district_id === districtId)
}

export function searchLocations(query: string): { upazilas: Upazila[]; matchedDistrictIds: string[] } {
  const q = query.trim().toLowerCase()
  if (!q) return { upazilas: [], matchedDistrictIds: [] }

  const matchedUpazilas = UPAZILAS.filter(u => 
    u.name_bn.includes(q) || 
    u.name_en.toLowerCase().includes(q) ||
    u.district_name_bn.includes(q) ||
    u.district_name_en.toLowerCase().includes(q)
  )

  const matchedDistrictIds = Array.from(new Set(matchedUpazilas.map(u => u.district_id)))

  return { upazilas: matchedUpazilas, matchedDistrictIds }
}
